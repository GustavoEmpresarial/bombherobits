import 'dotenv/config';
import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import Fastify from 'fastify';
import jwt from '@fastify/jwt';
import { prisma } from '../src/lib/prisma.js';
import { demoRoutes } from '../src/routes/demo.js';
import { meRoutes } from '../src/routes/me.js';
import { heroesRoutes } from '../src/routes/heroes.js';
import { dungeonRoutes } from '../src/routes/dungeon.js';
import { summonRoutes } from '../src/routes/summons.js';
import { worldRoutes } from '../src/routes/world.js';
import { sessionHasAccess } from '../src/lib/auth.js';
import { buyListing, listForSale, redeemInvite, worldState } from '../src/services/world.js';
import { cellBlocked } from '@herobits/shared';

after(() => prisma.$disconnect());
test('full demo persists gameplay, claims packs once, and cannot cross the live economy boundary', {skip:process.env.HEROBITS_TEST_DATABASE!=='1'}, async()=>{
  const app=Fastify(); await app.register(jwt,{secret:'disposable-demo-integration-secret'});
  for(const routes of [demoRoutes,meRoutes,heroesRoutes,dungeonRoutes,summonRoutes,worldRoutes])await app.register(routes);
  const ids:string[]=[];
  const previous=process.env.BMINER_EARLY_ACCESS_OPEN;process.env.BMINER_EARLY_ACCESS_OPEN='false';
  try{
    const created=await app.inject({method:'POST',url:'/demo/session',payload:{}});
    assert.equal(created.statusCode,200);
    const session=created.json();ids.push(session.user.id);
    const headers={authorization:`Bearer ${session.token}`};
    const call=async(url:string,payload?:unknown)=>{const result=await app.inject({method:payload===undefined?'GET':'POST',url,headers,...(payload===undefined?{}:{payload})});assert.equal(result.statusCode,200,result.body);return result.json();};
    assert.equal((await call('/me')).id,session.user.id);
    assert.equal((await call('/heroes')).length,18);
    assert.equal(await sessionHasAccess({id:session.user.id,wallet:session.user.wallet}),false,'demo flag is mandatory');
    assert.equal(await sessionHasAccess({id:session.user.id,wallet:'live-wallet',demo:true}),false);
    const run=await call('/dungeon/start',{});
    assert.equal(run.targets.length,60);
    assert(run.targets.every((t:{x:number;y:number})=>!cellBlocked(t.x,t.y)));
    const deployed=await call('/dungeon/deploy',{all:true});
    const hunters=deployed.heroes.filter((h:{status:string})=>h.status==='HUNTING');
    assert.equal(hunters.length,15);
    assert(hunters.every((h:{dungeonX:number;dungeonY:number})=>!cellBlocked(h.dungeonX,h.dungeonY)));
    await call(`/heroes/${hunters[0].id}/rest`,{});
    await call('/blacksmiths/buy',{tier:1});
    await call('/porters/buy',{});
    assert.equal((await call('/porters/toggle',{})).porterOn,false);
    const pack=await call('/heroes/summon',{count:5,requestId:randomUUID()});
    const batchId=pack.batch.id;
    await call(`/heroes/summons/${batchId}/reveal`,{});
    await call(`/heroes/summons/${batchId}/claim`,{});
    await call(`/heroes/summons/${batchId}/claim`,{});
    assert.equal((await call('/heroes')).length,23,'claim retry must not duplicate heroes');
    assert.equal((await call('/heroes/summons/pending')).length,0);
    assert((await call('/chest/withdraw',{})).net>0);
    const live=await prisma.user.create({data:{wallet:`qa-live-${randomUUID()}`,displayName:'Disposable live boundary test',inviteCode:randomUUID(),gold:5000}});ids.push(live.id);
    const liveToken=app.jwt.sign({id:live.id,wallet:live.wallet});
    assert.equal((await app.inject({url:'/me',headers:{authorization:`Bearer ${liveToken}`}})).statusCode,403);
    await assert.rejects(()=>redeemInvite(session.user.id,live.inviteCode!),/not found/);
    await assert.rejects(()=>redeemInvite(live.id,session.user.inviteCode),/not found/);
    const liveHero=await prisma.hero.create({data:{userId:live.id,class:'WARRIOR',rarity:'COMMON',atk:8,spd:1,stamina:100,maxStamina:100}});
    await listForSale(live.id,'HERO',liveHero.id,100);
    const listing=await prisma.listing.findFirstOrThrow({where:{sellerId:live.id}});
    await assert.rejects(()=>buyListing(session.user.id,listing.id),/gone/);
    assert.equal((await worldState(session.user.id)).listings.some(l=>l.id===listing.id),false);
    const demoHero=(await call('/heroes')).find((h:{status:string})=>h.status==='IDLE');
    await call('/market/list',{kind:'HERO',refId:demoHero.id,price:100});
    const demoListing=await prisma.listing.findFirstOrThrow({where:{sellerId:session.user.id}});
    await assert.rejects(()=>buyListing(live.id,demoListing.id),/gone/);
    assert.equal((await worldState(live.id)).listings.some(l=>l.id===demoListing.id),false);
    assert.equal((await prisma.hero.findUniqueOrThrow({where:{id:liveHero.id}})).userId,live.id);
    const other=await app.inject({method:'POST',url:'/demo/session',payload:{}});const guest=other.json();ids.push(guest.user.id);
    await redeemInvite(guest.user.id,session.user.inviteCode);
    assert.equal((await prisma.user.findUniqueOrThrow({where:{id:guest.user.id}})).referredBy,session.user.inviteCode);
  }finally{
    await app.close();
    await prisma.user.deleteMany({where:{id:{in:ids}}});
    if(previous===undefined)delete process.env.BMINER_EARLY_ACCESS_OPEN;else process.env.BMINER_EARLY_ACCESS_OPEN=previous;
  }
});
